def esc(s):
    out = []
    for ch in s:
        o = ord(ch)
        if o < 128:
            out.append(ch.replace("\\", "\\\\").replace('"', '\\"'))
        else:
            cp = o
            if cp > 0xFFFF:
                cp -= 0x10000
                hi = 0xD800 + (cp >> 10)
                lo = 0xDC00 + (cp & 0x3FF)
                out.append("\\u%04x\\u%04x" % (hi, lo))
            else:
                out.append("\\u%04x" % o)
    return "".join(out)


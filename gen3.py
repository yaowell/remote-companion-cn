FMT = re.compile(r'%@|%ld|%lu|%\.\df|%%')
def fmt_to_regex(tpl_key):
    # 返回 (regex_src, out_tpl) 或 None
    pat, out, gi = '', '', 0
    i = 0
    while i < len(tpl_key):
        c = tpl_key[i]
        if c == '%':
            m = re.match(r'%@|%ld|%lu|%\.1f|%\.2f|%%', tpl_key[i:])
            if m:
                s = m.group(0)
                if s == '%%':
                    pat += '%'
                elif s == '%@':
                    gi += 1; pat += '(.+)'; out += '{%d}' % (gi - 1)
                elif s in ('%ld', '%lu'):
                    gi += 1; pat += r'(\d+)'; out += '{%d}' % (gi - 1)
                elif s == '%.1f':
                    gi += 1; pat += r'(\d+\.\d)'; out += '{%d}' % (gi - 1)
                elif s == '%.2f':
                    gi += 1; pat += r'(\d+\.\d{2})'; out += '{%d}' % (gi - 1)
                i += len(s)
                continue
        pat += re.escape(c)
        i += 1
    return '^' + pat + '$', out

